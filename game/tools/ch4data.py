    return {'id': i, 'topic': topic, 'bloom': bloom, 'difficulty': diff, 'type': 'MCQ', 'stem': T(stem),
            'choices': [{'id': k, 'th': c} for k, c in zip('abcd', choices)], 'answer': [ans], 'explanation': T(expl), 'relatedCodex': cdx}
